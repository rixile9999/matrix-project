@main def tests(): Unit =
  val t1: Tree[Int] = Branch(Branch(Leaf(1), Leaf(2)), Leaf(3))
  val t2: Tree[Int] = Branch(Leaf(-5), Branch(Leaf(-2), Branch(Leaf(-9), Leaf(-7))))
  Judge.check("fold › 잎 값을 그대로 더함")(fold(t1)(x => x)(_ + _), 6)
  Judge.check("fold › 잎 하나")(fold(Leaf(4))(_ * 2)(_ + _), 8)
  Judge.check("fold › 왼쪽 결과가 g의 첫 인자")(fold(t1)(_.toString)(_ + _), "123")
  Judge.check("fold › 결과 타입이 다름")(fold(t1)(x => scala.List(x))(_ ++ _), scala.List(1, 2, 3))
  Judge.check("size › 잎 하나")(sizeViaFold(Leaf("a")), 1)
  Judge.check("size › 트리")(sizeViaFold(t1), 5)
  Judge.check("maximum › 일반")(maximumViaFold(t1), 3)
  Judge.check("maximum › 전부 음수")(maximumViaFold(t2), -2)
  Judge.check("maximum › 잎 하나")(maximumViaFold(Leaf(-1)), -1)
  Judge.check("depth › 잎 하나")(depthViaFold(Leaf(1)), 0)
  Judge.check("depth › 트리")(depthViaFold(t1), 2)
  Judge.check("depth › 한쪽으로 깊음")(depthViaFold(t2), 3)
  Judge.check("map › 값 변환")(mapViaFold(t1)(_ * 10), Branch(Branch(Leaf(10), Leaf(20)), Leaf(30)))
  Judge.check("map › 타입 변경")(mapViaFold(Branch(Leaf(1), Leaf(2)))(_.toString), Branch(Leaf("1"), Leaf("2")))
  Judge.check("map › 잎 하나")(mapViaFold(Leaf(1))(_ + 1), Leaf(2))
